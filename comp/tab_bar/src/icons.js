/**
 * Draws a tab vector icon in outline or filled mode with correct scaling and centering.
 * 
 * @param {CanvasRenderingContext2D} ctx - Target 2D rendering context
 * @param {string} type - Icon identifier ('home', 'cart', 'bag', 'mark', 'call', etc.)
 * @param {number} cx - Center X coordinate in pixels
 * @param {number} cy - Center Y coordinate in pixels
 * @param {number} size - Desired icon display size in pixels
 * @param {string} color - Fill/stroke color (e.g. '#1d1d1f')
 * @param {'outline'|'filled'} mode - Rendering mode
 */
export function drawTabVectorIcon(ctx, type, cx, cy, size, color, mode = 'outline') {
    const iconData = svgIconDefinitions[type];
    if (!iconData) return;
    const vb = iconData.viewBox || 24;
    const s = size / vb;

    ctx.save();
    ctx.translate(cx, cy);
    ctx.scale(s, s);
    ctx.translate(-vb * 0.5, -vb * 0.5);

    ctx.strokeStyle = color;
    ctx.fillStyle = color;
    ctx.lineWidth = iconData.strokeWidth || 1.7;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';

    const part = iconData[mode];
    if (part) {
        if (part.fill) {
            for (let i = 0; i < part.fill.length; i++) {
                ctx.fill(part.fill[i]);
            }
        }
        if (part.stroke) {
            for (let i = 0; i < part.stroke.length; i++) {
                ctx.stroke(part.stroke[i]);
            }
        }
    }
    ctx.restore();
}

